#include <string>
#include <vector>

void gcd_triple() {
    int a = 24, b = 36, c = 60;
    int g = a;
    for (int d = g; d >= 1; --d) {
        if (a % d == 0 && b % d == 0 && c % d == 0) { g = d; break; }
    }
    (void)g;
}

void sum_squares() {
    int acc = 0;
    for (int i = -5; i <= 5; ++i) acc += i * i;
    (void)acc;
}

void leading_zeros() {
    unsigned int n = 0b000101u;
    int zeros = 0;
    while ((n & 1u) == 0u) { zeros += 1; n >>= 1; }
    (void)zeros;
}

void triangular_number() {
    int n = 12;
    int tri = n * (n + 1) / 2;
    (void)tri;
}

extern "C" int lunar_hollow();
extern "C" void still_haven();
extern "C" void placid_maple();

int main() {
    gcd_triple();
    sum_squares();
    leading_zeros();
    triangular_number();
    still_haven();
    placid_maple();
    return lunar_hollow();
}
